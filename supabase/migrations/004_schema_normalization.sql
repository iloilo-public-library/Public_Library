-- Backfill condition_status on book_inventory based on damaged_copies / lost_copies / available_copies
UPDATE public.book_inventory
SET condition_status = CASE
  WHEN damaged_copies > 0 AND lost_copies > 0 THEN 'Damaged & Lost Copies'
  WHEN damaged_copies > 0 THEN 'Has Damaged Copies'
  WHEN lost_copies > 0 THEN 'Has Lost Copies'
  WHEN available_copies = 0 THEN 'Out of Stock'
  ELSE 'All Good'
END;

-- Auto-seed `public.book_copies` from existing `book_inventory` rows if empty
DO $$
DECLARE
  inv RECORD;
  c INT;
  cond VARCHAR(24);
  circ VARCHAR(24);
  acc VARCHAR(64);
  good_left INT;
  dmg_left INT;
  lost_left INT;
BEGIN
  FOR inv IN SELECT * FROM public.book_inventory LOOP
    IF NOT EXISTS (SELECT 1 FROM public.book_copies WHERE book_id = inv.book_id) THEN
      dmg_left := GREATEST(0, inv.damaged_copies);
      lost_left := GREATEST(0, inv.lost_copies);
      good_left := GREATEST(0, inv.available_copies);

      FOR c IN 1..GREATEST(1, LEAST(inv.volumes, 50)) LOOP
        IF c <= good_left THEN
          cond := 'Good';
          circ := 'Available';
        ELSIF c <= (good_left + dmg_left) THEN
          cond := 'Damaged';
          circ := 'Unusable';
        ELSIF c <= (good_left + dmg_left + lost_left) THEN
          cond := 'Lost';
          circ := 'Unusable';
        ELSE
          cond := 'Good';
          circ := 'Borrowed';
        END IF;

        acc := 'ICPL-' || LPAD(inv.book_id::TEXT, 4, '0') || '-C' || LPAD(c::TEXT, 2, '0');

        INSERT INTO public.book_copies (
          book_id, copy_number, accession_number, condition, circulation_status,
          condition_notes, shelf_location
        ) VALUES (
          inv.book_id,
          c,
          acc,
          cond,
          circ,
          CASE WHEN cond = 'Damaged' THEN 'Flagged for inspection/repair' ELSE '' END,
          inv.shelf_location
        )
        ON CONFLICT DO NOTHING;
      END LOOP;
    END IF;
  END LOOP;
END $$;


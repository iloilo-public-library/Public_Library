-- 1. ADD PHYSICAL COPY-LEVEL INVENTORY TABLE (`public.book_copies`)
-- Solves the IT Head's requirement: distinguish individual physical copies of a multi-copy
-- book by Accession Number & Copy Number, and sort/filter by Condition independently.
CREATE TABLE IF NOT EXISTS public.book_copies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id INTEGER NOT NULL REFERENCES public.books(id) ON DELETE CASCADE,
  copy_number INTEGER NOT NULL DEFAULT 1 CHECK (copy_number >= 1),
  accession_number VARCHAR(64) NOT NULL UNIQUE,
  condition VARCHAR(24) NOT NULL DEFAULT 'Good'
    CHECK (condition IN ('Good', 'Fair', 'Damaged', 'Lost', 'Under Repair')),
  circulation_status VARCHAR(24) NOT NULL DEFAULT 'Available'
    CHECK (circulation_status IN ('Available', 'Borrowed', 'Reserved', 'Unusable')),
  condition_notes TEXT DEFAULT '',
  shelf_location VARCHAR(120),
  acquired_at DATE DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (book_id, copy_number)
);

CREATE INDEX IF NOT EXISTS idx_book_copies_book_id ON public.book_copies (book_id);
CREATE INDEX IF NOT EXISTS idx_book_copies_condition ON public.book_copies (condition);
CREATE INDEX IF NOT EXISTS idx_book_copies_circulation ON public.book_copies (circulation_status);

DROP TRIGGER IF EXISTS trg_book_copies_updated_at ON public.book_copies;
CREATE TRIGGER trg_book_copies_updated_at
  BEFORE UPDATE ON public.book_copies
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.book_copies ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read book_copies" ON public.book_copies;
CREATE POLICY "Public read book_copies" ON public.book_copies FOR SELECT USING (TRUE);


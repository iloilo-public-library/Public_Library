CREATE TABLE IF NOT EXISTS public.event_reminders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id INTEGER NOT NULL REFERENCES public.events (id) ON DELETE CASCADE,
  remind_before_minutes INTEGER NOT NULL CHECK (remind_before_minutes IN (10, 30, 60, 1440)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (event_id, remind_before_minutes)
);

CREATE INDEX IF NOT EXISTS idx_event_reminders_event_id ON public.event_reminders (event_id);

CREATE TABLE IF NOT EXISTS public.event_reminder_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id INTEGER NOT NULL REFERENCES public.events (id) ON DELETE CASCADE,
  occurrence_date DATE NOT NULL,
  remind_before_minutes INTEGER NOT NULL,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  recipient_count INTEGER NOT NULL DEFAULT 0,
  UNIQUE (event_id, occurrence_date, remind_before_minutes)
);

CREATE INDEX IF NOT EXISTS idx_event_reminder_log_lookup
  ON public.event_reminder_log (event_id, occurrence_date);


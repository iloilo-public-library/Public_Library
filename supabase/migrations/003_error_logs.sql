CREATE TABLE IF NOT EXISTS public.error_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  level VARCHAR(20) NOT NULL DEFAULT 'error' CHECK (level IN ('error', 'security', 'warning', 'info')),
  source VARCHAR(40) NOT NULL DEFAULT 'API',
  route VARCHAR(255) NOT NULL DEFAULT '',
  method VARCHAR(12) NOT NULL DEFAULT 'GET',
  status_code INTEGER NOT NULL DEFAULT 500,
  message TEXT NOT NULL,
  details TEXT DEFAULT '',
  user_email VARCHAR(255) DEFAULT '',
  resolved BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_error_logs_level ON public.error_logs (level);
CREATE INDEX IF NOT EXISTS idx_error_logs_created_at ON public.error_logs (created_at DESC);

ALTER TABLE public.error_logs ENABLE ROW LEVEL SECURITY;

-- Service role key on the Next.js backend bypasses RLS safely; deny anon reads/writes.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'error_logs' AND policyname = 'Public insert client error logs'
  ) THEN
    CREATE POLICY "Public insert client error logs"
      ON public.error_logs FOR INSERT
      WITH CHECK (source IN ('Client', '404'));
  END IF;
END $$;
